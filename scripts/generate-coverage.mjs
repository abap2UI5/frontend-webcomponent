#!/usr/bin/env node
/*
 * The control coverage table: every control of portable profile v1
 * (profile/portable-v1.json) and every further control this frontend maps,
 * with the web component, the status (full / basic) and what "basic" leaves
 * out - from the control registry itself, so the table cannot drift.
 * Written into README.md between the coverage markers.
 *
 *   node scripts/generate-coverage.mjs           write
 *   node scripts/generate-coverage.mjs --check   fail when README.md is stale
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const { list, get } = await import('../src/render/registry.js');
await import('../src/render/controls/index.js');

const profile = JSON.parse(fs.readFileSync(path.join(ROOT, 'profile', 'portable-v1.json'), 'utf8'));
const v1 = Object.entries(profile.controls);

function webComponent(m) {
  if (!m) return '-';
  if (m.wc) return m.wc;
  if (m.tag) return m.tag.startsWith('ui5-') ? `\`${m.tag}\`` : `HTML \`<${m.tag}>\``;
  const src = m.render ? m.render.toString() : '';
  const tags = [...new Set([...src.matchAll(/'(ui5-[a-z-]+)'/g)].map((x) => x[1]))];
  if (/render: \(\) => null|^\(\) => null/.test(src) || src.trim() === '() => null') return 'none (no UI)';
  return tags.length ? tags.slice(0, 3).map((t) => `\`${t}\``).join(' + ') : 'HTML/CSS';
}

const row = (name, m) => `| ${name} | ${webComponent(m)} | ${m ? (m.status === 'basic' ? 'basic' : 'full') : '**missing**'} | ${m && m.note ? m.note.replace(/\|/g, '\\|') : ''} |`;

export function table() {
  const lines = [];
  const covered = v1.filter(([n]) => get(n));
  lines.push(`Portable profile v1: **${covered.length} of ${v1.length}** controls mapped (${v1.filter(([n]) => get(n) && get(n).status !== 'basic').length} full, ${v1.filter(([n]) => get(n) && get(n).status === 'basic').length} basic).`);
  lines.push('');
  lines.push('| UI5 control (profile v1) | rendered as | status | basic: what is left out |');
  lines.push('|---|---|---|---|');
  for (const [n, spec] of v1) lines.push(row(`${n}${spec.tolerated ? ' (tolerated)' : ''}`, get(n)));
  const extra = list().map((m) => m.name).filter((n) => !profile.controls[n]).sort();
  lines.push('');
  lines.push(`Beyond v1 (${extra.length}):`);
  lines.push('');
  lines.push('| UI5 control | rendered as | status | basic: what is left out |');
  lines.push('|---|---|---|---|');
  for (const n of extra) lines.push(row(n, get(n)));
  return lines.join('\n');
}

const START = '<!-- coverage:start (generated by scripts/generate-coverage.mjs) -->';
const END = '<!-- coverage:end -->';
const readme = path.join(ROOT, 'README.md');
const text = fs.readFileSync(readme, 'utf8');
const i = text.indexOf(START);
const j = text.indexOf(END);
if (i < 0 || j < 0) {
  console.error('generate-coverage: README.md has no coverage markers');
  process.exit(1);
}
const next = `${text.slice(0, i + START.length)}\n${table()}\n${text.slice(j)}`;
if (process.argv.includes('--check')) {
  if (next !== text) {
    console.error('generate-coverage: README.md coverage table is stale - run node scripts/generate-coverage.mjs');
    process.exit(1);
  }
  console.log('generate-coverage: README.md is up to date');
} else {
  fs.writeFileSync(readme, next);
  console.log('generate-coverage: README.md updated');
}
